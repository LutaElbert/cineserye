import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { openEditor, waitForSaved } from './helpers';

test('Story editor preserves geometry, retains drafts on Escape, synchronizes brief and supports undo', async ({ page }) => {
  const posts: string[] = [];
  page.on('request', (request) => { if (request.method() === 'POST' && request.url().includes('/api/cinema/')) posts.push(request.url()); });
  await openEditor(page);
  const story = page.locator('.react-flow__node[data-id="story-premise"]');
  const geometry = () => page.locator('.react-flow__node').evaluateAll((nodes) => nodes.map((node) => ({ id: (node as HTMLElement).dataset.id, transform: (node as HTMLElement).style.transform, width: (node as HTMLElement).style.width, height: (node as HTMLElement).style.height })));
  const before = await geometry();
  await story.dblclick();
  const editor = page.getByRole('region', { name: 'Story premise layer editor', exact: true });
  await expect(editor).toBeVisible();
  await editor.getByLabel('Layer title', { exact: true }).fill('The Last Screening');
  await editor.getByRole('textbox', { name: 'Premise for development', exact: true }).fill('A cinema reveals tomorrow.');
  expect((await geometry()).filter((node) => node.id !== 'story-premise')).toEqual(before.filter((node) => node.id !== 'story-premise'));
  await expect(story).toHaveCSS('width', '440px');
  await expect(editor.getByRole('status').last()).toHaveText('Saved on this device');
  await expect(page.locator('.inspector-panel')).toContainText('Editing on canvas');
  const results = await new AxeBuilder({ page }).include('.premise-expanded-node').analyze();
  expect(results.violations).toEqual([]);
  await editor.getByRole('textbox', { name: 'Premise for development', exact: true }).press('Escape');
  await expect(editor).toHaveCount(0);
  expect(await geometry()).toEqual(before);
  await expect(story).toContainText('A cinema reveals tomorrow.');
  await waitForSaved(page); await page.reload();
  await expect(page.locator('main[data-ready="true"]')).toBeVisible();
  await story.dblclick();
  await page.getByRole('button', { name: 'Focus story editor', exact: true }).click();
  await expect(editor.getByRole('textbox', { name: 'Premise for development', exact: true })).toHaveValue('A cinema reveals tomorrow.');
  await editor.getByLabel('Layer title', { exact: true }).fill('Changed again');
  await editor.getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(story).toContainText('The Last Screening');
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await expect(story).toContainText('Changed again');
  expect(posts).toEqual([]);
});

test('Scene review targets edited scene and does not dispatch generation', async ({ page }) => {
  let posts = 0; page.on('request', (request) => { if (request.method() === 'POST' && request.url().includes('/api/cinema/')) posts++; });
  await openEditor(page);
  await page.locator('.react-flow__node[data-id="scene-01"]').dblclick();
  await page.getByRole('button', { name: 'Focus layer editor', exact: true }).click();
  const editor = page.getByRole('region', { name: 'Scene layer editor', exact: true });
  expect(await editor.evaluate((element) => element.closest<HTMLElement>('.react-flow__node')?.dataset.id)).toBe('scene-01');
  await editor.getByLabel('Layer description', { exact: true }).fill('Mara finds a flickering projector.');
  await editor.getByRole('button', { name: 'Review shot plan', exact: true }).click();
  const review = page.getByRole('region', { name: 'Generate shot plan', exact: true });
  await expect(review).toBeVisible();
  expect(await review.evaluate((element) => element.closest<HTMLElement>('.react-flow__node')?.dataset.id)).toBe('scene-01');
  await expect(page.locator('dialog[open]')).toHaveCount(0);
  await expect(review.locator('#scene-brief-sceneText')).toHaveValue('Mara finds a flickering projector.');
  expect(posts).toBe(0);
});

test('locked manual layer is inspectable and mobile editor stays inside viewport', async ({ page }) => {
  await openEditor(page);
  const scene = page.locator('.react-flow__node[data-id="scene-01"]');
  await scene.click();
  await page.getByLabel('Lock layer', { exact: true }).check();
  await scene.dblclick();
  await page.getByRole('button', { name: 'Focus layer editor', exact: true }).click();
  const editor = page.getByRole('region', { name: 'Scene layer editor', exact: true });
  await expect(editor.getByLabel('Layer title', { exact: true })).toBeDisabled();
  await expect(editor.getByRole('button', { name: 'Review shot plan' })).toBeDisabled();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Focus layer editor', exact: true }).click();
  await expect(page.locator('dialog[open]')).toHaveCount(0);
  const box = await editor.boundingBox(); expect(box).not.toBeNull();
  expect(box!.x).toBeGreaterThanOrEqual(0); expect(box!.x + box!.width).toBeLessThanOrEqual(391);
  await editor.getByRole('button', { name: 'Done', exact: true }).click();
  await expect(editor).toHaveCount(0);
});

